def train_stabilized_episodic_linear_probe(s_features, s_labels, num_classes=5, num_epochs=100, lr=0.005):
    """
    Inizializza e addestra un Linear Probe sulle feature estratte dal Supervisor (OpenAI CLIP L/14).
    Risolve il runtime crash sincronizzando dinamicamente il tipo di dato a precisione ridotta (Half).
    """
    feature_dim = s_features.size(-1)
    linear_probe = nn.Linear(feature_dim, num_classes).to(DEVICE)

    # CRITICAL DTYPE FIX: Converte i pesi interni del livello lineare al dtype Half/float16 delle feature di CLIP
    linear_probe = linear_probe.to(dtype=s_features.dtype)

    # Forte L2 regularization (weight_decay=0.1) per forzare barriere decisionali ultra-rigide
    optimizer = optim.Adam(linear_probe.parameters(), lr=lr, weight_decay=1e-1)
    criterion = nn.CrossEntropyLoss()

    # Cast obbligatorio a Long integer per prevenire nll_loss_forward CUDA index error
    s_labels_t = torch.tensor(s_labels, dtype=torch.long, device=DEVICE)

    for _ in range(num_epochs):
        optimizer.zero_grad()

        # Sincronizzazione ed esecuzione in smoothed-temperature
        outputs = linear_probe(s_features) / TEMPERATURE_TAU
        loss = criterion(outputs, s_labels_t)

        loss.backward()
        optimizer.step()

    linear_probe.eval()
    return linear_probe


